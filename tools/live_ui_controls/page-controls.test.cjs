const assert = require('node:assert/strict');
const fs = require('node:fs');
const {pageKeys, valueOf, mergeChanges, decoratePacket, draftKey, draftChanges, inputValue} = require('./page-controls.js');
const schema = JSON.parse(fs.readFileSync(require('node:path').join(__dirname, 'schema.json'), 'utf8'));
const pages = ['account-builder', 'home-builder', 'checkout-builder','catalog-builder','product-builder'];
const mapped = pages.flatMap(page => pageKeys(page, schema));
assert.equal(mapped.length, Object.keys(schema).length);
assert.equal(new Set(mapped).size, 112);
assert.equal(pageKeys('account-builder', schema).length, 31);
assert.equal(pageKeys('home-builder', schema).length, 7);
assert.equal(pageKeys('checkout-builder', schema).length, 56);
assert.equal(pageKeys('catalog-builder', schema).length, 10);
assert.equal(pageKeys('product-builder', schema).length, 8);
assert.equal(valueOf({schema, values:{}}, 'logout_height'), 38);
assert.equal(valueOf({schema, values:{cart_pulse_enabled:false}}, 'cart_pulse_enabled'), false);
assert.equal(valueOf({schema, values:{}}, 'cart_item_image_radius'), null);
assert.equal(inputValue({value:'',valueAsNumber:NaN},schema.cart_item_image_radius),null);
assert.equal(inputValue({value:'0',valueAsNumber:0},schema.cart_item_image_radius),0);
assert.equal(inputValue({value:'compact'},schema.cart_layout),'compact');
const baseline = {logout_height:38, auth_title_en:''};
assert.deepEqual(mergeChanges(schema, baseline, {logout_height:40}, {cart_pulse_scale:1.5}), {logout_height:40, cart_pulse_scale:1.5});
assert.throws(() => mergeChanges(schema, baseline, {logout_height:40}, {logout_height:42}));
assert.deepEqual(mergeChanges(schema, baseline, {logout_height:40}, {logout_height:40}), {logout_height:40});
assert.deepEqual(mergeChanges(schema, {auth_title_en:'Welcome'}, {auth_title_en:''}, {auth_title_en:'Welcome',logout_height:42}), {auth_title_en:'',logout_height:42});
assert.throws(() => mergeChanges(schema, {}, {unknown:1}, {}));
const packet = {page:'account', layout:{page:'account'}, layouts:{home:{settings:{merchant:'retained'}, blocks:[{id:1}]}, account:{page:'account'}}, demo_catalog:{products:[1]}};
const before = JSON.stringify(packet);
const controls = {auth_title_en:'Draft title', cart_pulse_enabled:false, logout_height:42};
const decorated = decoratePacket(packet, controls);
assert.deepEqual(decorated.layouts.home.settings, {merchant:'retained', ui_controls_v1:controls});
assert.equal(JSON.stringify(packet), before, 'Do not modify cached layout packets');
assert.equal(decorated.demo_catalog, packet.demo_catalog);
assert.equal(decorated.layout, packet.layout);
const homePacket = decoratePacket({...packet, page:'home', home:packet.layouts.home}, controls);
assert.equal(homePacket.layout, homePacket.layouts.home);
assert.equal(homePacket.home, packet.layouts.home);
assert.equal(Object.hasOwn(decoratePacket({...packet, page:'home'},controls),'home'), false);
assert.deepEqual(draftChanges(schema, {auth_background:'#FFFFFF'}, {auth_background:inputValue({value:'#ffffff'},schema.auth_background)}), {});
assert.notEqual(draftKey('merchant-a','account-builder'), draftKey('merchant-b','account-builder'));
assert.notEqual(draftKey('merchant-a','account-builder'), draftKey('merchant-a','home-builder'));
assert.deepEqual(draftChanges(schema, {logout_height:38,auth_title_en:''}, {logout_height:42,auth_title_en:'',unknown:1}), {logout_height:42});
console.log('PASS draft preview preserves layouts, typed controls and merchant/screen isolation');
console.log('PASS: all 112 controls mapped once; defaults, inherited sizes, zero radius, choices, page isolation, concurrent edits and reset');
