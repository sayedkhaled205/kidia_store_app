"""Keep the server and mobile public-controls contract identical."""
import argparse
import json
from pathlib import Path

root = Path(__file__).resolve().parents[1]
schema = json.loads((root / 'tools/live_ui_controls/schema.json').read_text(encoding='utf-8'))
parser = argparse.ArgumentParser()
parser.add_argument('--check', action='store_true')
args = parser.parse_args()
outputs = {
    'tools/live_ui_controls/backend/app/Services/live-ui-controls-v1.json':
        json.dumps(schema, ensure_ascii=False, indent=2) + '\n',
    'lib/core/app_design/app_ui_control_schema.dart':
        "// Generated by tool/generate_app_ui_controls.py.\n"
        "import 'dart:convert';\n\n"
        "final Map<String, dynamic> appUiControlSchema =\n"
        "    jsonDecode(\n"
        "          r'''" + json.dumps(schema, ensure_ascii=True, separators=(',', ':')) + "''',\n"
        "        )\n"
        "        as Map<String, dynamic>;\n",
}
for relative, content in outputs.items():
    target = root / relative
    if args.check:
        if target.read_text(encoding='utf-8') != content:
            raise SystemExit(f'Contract drift: {relative}; run tool/generate_app_ui_controls.py')
    else:
        target.write_text(content, encoding='utf-8', newline='\n')
print(f'Public controls contract: {len(schema)} fields, server/mobile match')
