<?php
/**
 * Opt-in Native Store API safety contract. Not activated by merely including it.
 *
 * Review installed Woo source and explicitly install the returned DDL before
 * wiring register(). No schema creation, QA bypass, gateway, or order replay is
 * performed here. Unknown attempts are durable and have NO automatic expiry.
 *
 * @package MobiShop
 */

defined( 'ABSPATH' ) || exit;

/** Storage seam; the production implementation below uses transactional SQL. */
interface MobiShop_Native_Checkout_Store50 {
	public function ready(): bool;
	public function cart_customer( string $cart_user ): ?int;
	public function cart_empty( string $cart_user ): bool;
	public function claim( array $claim ): array;
	public function reject_before_dispatch( array $claim ): array;
	public function find( string $buyer, string $attempt ): ?array;
	public function associate( string $buyer, string $attempt, int $order_id ): bool;
	public function passed( string $buyer, string $attempt ): bool;
	public function finished( string $buyer, string $attempt ): bool;
	public function settle( string $buyer, string $attempt, string $state, string $payment ): bool;
	public function owns_cart( string $cart, string $buyer ): bool;
}

/** Durable, unique buyer/attempt/cart claims; no raw credentials or PII stored. */
final class MobiShop_Native_Checkout_Wpdb50 implements MobiShop_Native_Checkout_Store50 {
	private object $db;
	private array $tables;

	public function __construct( ?object $db = null ) {
		$this->db = $db ?? $GLOBALS['wpdb'];
		$prefix = (string) ( $this->db->prefix ?? '' );
		if ( ! preg_match( '/^[A-Za-z0-9_]+$/D', $prefix ) ) {
			throw new InvalidArgumentException( 'Invalid Native checkout table prefix.' );
		}
		$this->tables = array(
			'buyers' => $prefix . 'mobishop_native_checkout50_buyers',
			'attempts' => $prefix . 'mobishop_native_checkout50_attempts',
			'carts' => $prefix . 'mobishop_native_checkout50_carts',
			'sessions' => $prefix . 'woocommerce_sessions',
			'config' => $prefix . 'mobishop_native_checkout50_config',
		);
	}

	/** Explicit activation API: return SQL only. Does NOT execute any SQL. */
	public function installation_sql(): array {
		if ( ! self::key_configured() ) {
			throw new RuntimeException( 'Explicit immutable Native checkout installation key is required before setup.' );
		}
		return array(
			"CREATE TABLE {$this->tables['buyers']} (buyer_scope char(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL, active_attempt char(64) CHARACTER SET ascii COLLATE ascii_bin NULL, PRIMARY KEY (buyer_scope)) ENGINE=InnoDB",
			"CREATE TABLE {$this->tables['attempts']} (buyer_scope char(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL, attempt_hash char(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL, payload_hash char(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL, cart_scope char(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL, customer_id bigint unsigned NOT NULL, order_id bigint unsigned NOT NULL DEFAULT 0, state varchar(32) CHARACTER SET ascii COLLATE ascii_bin NOT NULL, payment_status varchar(16) CHARACTER SET ascii COLLATE ascii_bin NOT NULL DEFAULT '', guard_passed tinyint unsigned NOT NULL DEFAULT 0, dispatch_finished tinyint unsigned NOT NULL DEFAULT 0, created_at datetime NOT NULL, PRIMARY KEY (buyer_scope, attempt_hash)) ENGINE=InnoDB",
			"CREATE TABLE {$this->tables['carts']} (cart_scope char(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL, buyer_scope char(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL, PRIMARY KEY (cart_scope)) ENGINE=InnoDB",
			"CREATE TABLE {$this->tables['config']} (id tinyint unsigned NOT NULL, key_fingerprint char(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL, PRIMARY KEY (id)) ENGINE=InnoDB",
			"INSERT INTO {$this->tables['config']} (id, key_fingerprint) VALUES (1, '" . hash( 'sha256', MOBISHOP_NATIVE_CHECKOUT50_HMAC_KEY ) . "')",
		);
	}

	/** Dedicated immutable installation key, never generated by register(). */
	public static function key_configured(): bool {
		return defined( 'MOBISHOP_NATIVE_CHECKOUT50_HMAC_KEY' ) && is_string( MOBISHOP_NATIVE_CHECKOUT50_HMAC_KEY ) && 1 === preg_match( '/^[a-f0-9]{64}$/D', MOBISHOP_NATIVE_CHECKOUT50_HMAC_KEY );
	}

	/** Fail closed unless exact transactional tables, columns and PKs exist. */
	public function ready(): bool {
		if ( ! self::key_configured() ) {
			return false;
		}
		// Do not implicitly commit a transaction started by another plugin.
		if ( '0' !== (string) $this->db->get_var( 'SELECT @@in_transaction' ) ) {
			return false;
		}
		$spec = array(
			'buyers' => array( 'buyer_scope' => 'char(64)', 'active_attempt' => 'char(64)' ),
			'attempts' => array( 'buyer_scope' => 'char(64)', 'attempt_hash' => 'char(64)', 'payload_hash' => 'char(64)', 'cart_scope' => 'char(64)', 'customer_id' => 'bigint unsigned', 'order_id' => 'bigint unsigned', 'state' => 'varchar(32)', 'payment_status' => 'varchar(16)', 'guard_passed' => 'tinyint unsigned', 'dispatch_finished' => 'tinyint unsigned', 'created_at' => 'datetime' ),
			'carts' => array( 'cart_scope' => 'char(64)', 'buyer_scope' => 'char(64)' ),
			'config' => array( 'id' => 'tinyint unsigned', 'key_fingerprint' => 'char(64)' ),
		);
		foreach ( $spec as $name => $fields ) {
			$table = $this->tables[ $name ];
			$status = $this->db->get_row( $this->db->prepare( 'SHOW TABLE STATUS WHERE Name = %s', $table ), ARRAY_A );
			if ( ! is_array( $status ) || 'InnoDB' !== ( $status['Engine'] ?? '' ) || ( $status['Name'] ?? '' ) !== $table ) {
				return false;
			}
			$columns = $this->db->get_results( "SHOW FULL COLUMNS FROM `{$table}`", ARRAY_A );
			if ( ! is_array( $columns ) || count( $columns ) !== count( $fields ) ) {
				return false;
			}
			foreach ( $columns as $column ) {
				$field = $column['Field'] ?? '';
				$type = preg_replace( '/\(\d+\)/', '', strtolower( (string) ( $column['Type'] ?? '' ) ) );
				$expected = $fields[ $field ] ?? null;
				if ( null === $expected || $type !== preg_replace( '/\(\d+\)/', '', $expected ) ) {
					return false;
				}
				if ( str_contains( $expected, 'char(' ) && ( ( $column['Collation'] ?? '' ) !== 'ascii_bin' || strtolower( (string) $column['Type'] ) !== $expected ) ) {
					return false;
				}
				if ( ( 'buyers' !== $name || 'active_attempt' !== $field ) && 'NO' !== ( $column['Null'] ?? '' ) ) {
					return false;
				}
				if ( 'buyers' === $name && 'active_attempt' === $field && ( 'YES' !== ( $column['Null'] ?? '' ) || null !== ( $column['Default'] ?? null ) ) ) {
					return false;
				}
				if ( 'attempts' === $name && in_array( $field, array( 'order_id', 'guard_passed', 'dispatch_finished', 'payment_status' ), true ) && (string) ( $column['Default'] ?? null ) !== ( 'payment_status' === $field ? '' : '0' ) ) {
					return false;
				}
			}
			$indexes = $this->db->get_results( "SHOW INDEX FROM `{$table}`", ARRAY_A );
			$primary = array();
			if ( ! is_array( $indexes ) ) {
				return false;
			}
			foreach ( $indexes as $index ) {
				if ( 'PRIMARY' === ( $index['Key_name'] ?? '' ) && 0 === (int) ( $index['Non_unique'] ?? 1 ) && empty( $index['Sub_part'] ) ) {
					$primary[ (int) $index['Seq_in_index'] ] = $index['Column_name'];
				}
			}
			ksort( $primary );
			$expected = 'attempts' === $name ? array( 'buyer_scope', 'attempt_hash' ) : array( 'config' === $name ? 'id' : ( 'carts' === $name ? 'cart_scope' : 'buyer_scope' ) );
			if ( array_values( $primary ) !== $expected ) {
				return false;
			}
		}
		$fingerprint = $this->db->get_var( "SELECT key_fingerprint FROM `{$this->tables['config']}` WHERE id = 1" );
		return is_string( $fingerprint ) && hash_equals( hash( 'sha256', MOBISHOP_NATIVE_CHECKOUT50_HMAC_KEY ), $fingerprint );
	}

	/** Read Woo's stored session, permitting arrays only, before core mutates it. */
	public function cart_customer( string $cart_user ): ?int {
		$row = $this->db->get_row( $this->db->prepare( "SELECT session_value, session_expiry FROM `{$this->tables['sessions']}` WHERE session_key = %s", $cart_user ), ARRAY_A );
		if ( ! is_array( $row ) || (int) ( $row['session_expiry'] ?? 0 ) <= time() || ! is_string( $row['session_value'] ?? null ) ) {
			return null;
		}
		$data = @unserialize( $row['session_value'], array( 'allowed_classes' => false ) );
		if ( ! is_array( $data ) ) {
			return null;
		}
		$customer = $data['customer'] ?? array();
		if ( is_string( $customer ) ) {
			$customer = @unserialize( $customer, array( 'allowed_classes' => false ) );
		}
		if ( ! is_array( $customer ) ) {
			return null;
		}
		$id = $customer['id'] ?? '0';
		return ( is_int( $id ) || is_string( $id ) ) && preg_match( '/^[0-9]{1,18}$/D', (string) $id ) ? (int) $id : null;
	}

	/** Read only persisted cart state, not an unflushed in-memory empty cart. */
	public function cart_empty( string $cart_user ): bool {
		$row = $this->db->get_row( $this->db->prepare( "SELECT session_value, session_expiry FROM `{$this->tables['sessions']}` WHERE session_key = %s", $cart_user ), ARRAY_A );
		if ( ! empty( $this->db->last_error ) ) {
			return false;
		}
		if ( null === $row ) {
			return true; // A completed dispatch may have deleted its session.
		}
		if ( ! is_array( $row ) || ! is_string( $row['session_value'] ?? null ) ) {
			return false;
		}
		$data = @unserialize( $row['session_value'], array( 'allowed_classes' => false ) );
		if ( ! is_array( $data ) ) {
			return false;
		}
		$cart = $data['cart'] ?? array();
		if ( is_string( $cart ) ) {
			$cart = @unserialize( $cart, array( 'allowed_classes' => false ) );
		}
		return is_array( $cart ) && array() === $cart;
	}

	/** Atomically serialize a buyer and permanently bind adopted guest carts. */
	public function claim( array $claim ): array {
		$buyer = $claim['buyer_scope'];
		$attempt = $claim['attempt_hash'];
		if ( '0' !== (string) $this->db->get_var( 'SELECT @@in_transaction' ) || false === $this->db->query( 'START TRANSACTION' ) ) {
			return array( 'result' => 'unavailable' );
		}
		try {
			$this->query( $this->db->prepare( "INSERT IGNORE INTO `{$this->tables['buyers']}` (buyer_scope, active_attempt) VALUES (%s, NULL)", $buyer ) );
			$owner = $this->db->get_row( $this->db->prepare( "SELECT active_attempt FROM `{$this->tables['buyers']}` WHERE buyer_scope = %s FOR UPDATE", $buyer ), ARRAY_A );
			if ( ! is_array( $owner ) ) {
				throw new RuntimeException( 'Buyer claim unavailable.' );
			}
			$existing = $this->find( $buyer, $attempt );
			if ( $existing ) {
				$this->query( 'COMMIT' );
				return array( 'result' => hash_equals( $existing['payload_hash'], $claim['payload_hash'] ) ? 'existing' : 'conflict', 'attempt' => $existing );
			}
			if ( ! empty( $owner['active_attempt'] ) ) {
				$this->query( 'ROLLBACK' );
				return array( 'result' => 'blocked' );
			}
			$orphan = $this->db->get_row( $this->db->prepare( "SELECT attempt_hash FROM `{$this->tables['attempts']}` WHERE buyer_scope = %s AND state = 'in_progress' LIMIT 1 FOR UPDATE", $buyer ), ARRAY_A );
			if ( ! empty( $this->db->last_error ) ) {
				throw new RuntimeException( 'Unresolved attempt lookup unavailable.' );
			}
			if ( is_array( $orphan ) ) {
				$this->query( 'ROLLBACK' );
				return array( 'result' => 'blocked' );
			}
			$this->query( $this->db->prepare( "INSERT IGNORE INTO `{$this->tables['carts']}` (cart_scope, buyer_scope) VALUES (%s, %s)", $claim['cart_scope'], $buyer ) );
			$cart = $this->db->get_row( $this->db->prepare( "SELECT buyer_scope FROM `{$this->tables['carts']}` WHERE cart_scope = %s FOR UPDATE", $claim['cart_scope'] ), ARRAY_A );
			if ( ! is_array( $cart ) || ! hash_equals( $buyer, (string) $cart['buyer_scope'] ) ) {
				$this->query( 'ROLLBACK' );
				return array( 'result' => 'cart_conflict' );
			}
			$this->query( $this->db->prepare( "INSERT INTO `{$this->tables['attempts']}` (buyer_scope, attempt_hash, payload_hash, cart_scope, customer_id, state, created_at) VALUES (%s, %s, %s, %s, %d, 'in_progress', %s)", $buyer, $attempt, $claim['payload_hash'], $claim['cart_scope'], $claim['customer_id'], gmdate( 'Y-m-d H:i:s' ) ) );
			if ( 1 !== $this->db->query( $this->db->prepare( "UPDATE `{$this->tables['buyers']}` SET active_attempt = %s WHERE buyer_scope = %s AND active_attempt IS NULL", $attempt, $buyer ) ) ) {
				throw new RuntimeException( 'Buyer claim failed.' );
			}
			$this->query( 'COMMIT' );
			return array( 'result' => 'claimed' );
		} catch ( Throwable $error ) {
			$this->db->query( 'ROLLBACK' );
			return array( 'result' => 'unavailable' );
		}
	}

	public function find( string $buyer, string $attempt ): ?array {
		$row = $this->db->get_row( $this->db->prepare( "SELECT * FROM `{$this->tables['attempts']}` WHERE buyer_scope = %s AND attempt_hash = %s", $buyer, $attempt ), ARRAY_A );
		if ( ! empty( $this->db->last_error ) ) {
			throw new RuntimeException( 'Attempt lookup unavailable.' );
		}
		return is_array( $row ) ? $row : null;
	}

	/**
	 * Immutable rejection tombstone, only called before the endpoint callback.
	 * Serialize with claim() using the SAME buyer lock; absence alone is not proof.
	 * No active attempt is cleared, cart adopted, or existing attempt overwritten.
	 */
	public function reject_before_dispatch( array $claim ): array {
		$buyer = $claim['buyer_scope'];
		$attempt = $claim['attempt_hash'];
		if ( '0' !== (string) $this->db->get_var( 'SELECT @@in_transaction' ) || false === $this->db->query( 'START TRANSACTION' ) ) {
			return array( 'result' => 'unavailable' );
		}
		try {
			$this->query( $this->db->prepare( "INSERT IGNORE INTO `{$this->tables['buyers']}` (buyer_scope, active_attempt) VALUES (%s, NULL)", $buyer ) );
			$owner = $this->db->get_row( $this->db->prepare( "SELECT active_attempt FROM `{$this->tables['buyers']}` WHERE buyer_scope = %s FOR UPDATE", $buyer ), ARRAY_A );
			if ( ! is_array( $owner ) ) {
				throw new RuntimeException( 'Buyer rejection claim unavailable.' );
			}
			$existing = $this->find( $buyer, $attempt );
			if ( $existing ) {
				$this->query( 'COMMIT' );
				return array( 'result' => 'existing', 'attempt' => $existing );
			}
			if ( ! empty( $owner['active_attempt'] ) ) {
				$this->query( 'ROLLBACK' );
				return array( 'result' => 'blocked' );
			}
			$orphan = $this->db->get_row( $this->db->prepare( "SELECT attempt_hash FROM `{$this->tables['attempts']}` WHERE buyer_scope = %s AND state = 'in_progress' LIMIT 1 FOR UPDATE", $buyer ), ARRAY_A );
			if ( ! empty( $this->db->last_error ) ) {
				throw new RuntimeException( 'Unresolved rejection lookup unavailable.' );
			}
			if ( is_array( $orphan ) ) {
				$this->query( 'ROLLBACK' );
				return array( 'result' => 'blocked' );
			}
			$this->query( $this->db->prepare( "INSERT INTO `{$this->tables['attempts']}` (buyer_scope, attempt_hash, payload_hash, cart_scope, customer_id, state, dispatch_finished, created_at) VALUES (%s, %s, %s, %s, %d, 'rejected_before_dispatch', 1, %s)", $buyer, $attempt, $claim['payload_hash'], $claim['cart_scope'], $claim['customer_id'], gmdate( 'Y-m-d H:i:s' ) ) );
			$row = $this->find( $buyer, $attempt );
			if ( ! $row ) {
				throw new RuntimeException( 'Durable rejection unavailable.' );
			}
			$this->query( 'COMMIT' );
			return array( 'result' => 'rejected', 'attempt' => $row );
		} catch ( Throwable $error ) {
			$this->db->query( 'ROLLBACK' );
			return array( 'result' => 'unavailable' );
		}
	}

	public function associate( string $buyer, string $attempt, int $order_id ): bool {
		$result = $this->db->query( $this->db->prepare( "UPDATE `{$this->tables['attempts']}` SET order_id = %d WHERE buyer_scope = %s AND attempt_hash = %s AND state = 'in_progress' AND (order_id = 0 OR order_id = %d)", $order_id, $buyer, $attempt, $order_id ) );
		$row = $this->find( $buyer, $attempt );
		return false !== $result && $row && (int) $row['order_id'] === $order_id;
	}

	public function passed( string $buyer, string $attempt ): bool {
		$result = $this->db->query( $this->db->prepare( "UPDATE `{$this->tables['attempts']}` SET guard_passed = 1 WHERE buyer_scope = %s AND attempt_hash = %s AND state = 'in_progress' AND order_id > 0", $buyer, $attempt ) );
		$row = $this->find( $buyer, $attempt );
		return false !== $result && $row && 1 === (int) $row['guard_passed'];
	}

	public function finished( string $buyer, string $attempt ): bool {
		$result = $this->db->query( $this->db->prepare( "UPDATE `{$this->tables['attempts']}` SET dispatch_finished = 1 WHERE buyer_scope = %s AND attempt_hash = %s AND state = 'in_progress'", $buyer, $attempt ) );
		$row = $this->find( $buyer, $attempt );
		return false !== $result && $row && 1 === (int) $row['dispatch_finished'];
	}

	/** Only exact pre-payment rejection or authoritative created order resolves. */
	public function settle( string $buyer, string $attempt, string $state, string $payment ): bool {
		if ( ! in_array( $state, array( 'rejected_before_payment', 'order_created' ), true ) || ! in_array( $payment, array( '', 'success', 'unknown', 'pending' ), true ) || ( 'pending' === $payment && 'order_created' !== $state ) ) {
			return false;
		}
		if ( '0' !== (string) $this->db->get_var( 'SELECT @@in_transaction' ) || false === $this->db->query( 'START TRANSACTION' ) ) {
			return false;
		}
		try {
			$owner = $this->db->get_row( $this->db->prepare( "SELECT active_attempt FROM `{$this->tables['buyers']}` WHERE buyer_scope = %s FOR UPDATE", $buyer ), ARRAY_A );
			$row = $this->find( $buyer, $attempt );
			if ( ! is_array( $owner ) || ! $row || 'in_progress' !== $row['state'] || 1 !== (int) $row['dispatch_finished'] || ( $owner['active_attempt'] ?? null ) !== $attempt || ( 'order_created' === $state && ( (int) $row['order_id'] <= 0 || 1 !== (int) $row['guard_passed'] ) ) ) {
				throw new RuntimeException( 'Attempt settlement unavailable.' );
			}
			$this->query( $this->db->prepare( "UPDATE `{$this->tables['attempts']}` SET state = %s, payment_status = %s WHERE buyer_scope = %s AND attempt_hash = %s AND state = 'in_progress'", $state, $payment, $buyer, $attempt ) );
			$this->query( $this->db->prepare( "UPDATE `{$this->tables['buyers']}` SET active_attempt = NULL WHERE buyer_scope = %s AND active_attempt = %s", $buyer, $attempt ) );
			$this->query( 'COMMIT' );
			return true;
		} catch ( Throwable $error ) {
			$this->db->query( 'ROLLBACK' );
			return false;
		}
	}

	public function owns_cart( string $cart, string $buyer ): bool {
		$actual = $this->db->get_var( $this->db->prepare( "SELECT buyer_scope FROM `{$this->tables['carts']}` WHERE cart_scope = %s", $cart ) );
		return is_string( $actual ) && hash_equals( $buyer, $actual );
	}

	private function query( string $sql ): void {
		if ( false === $this->db->query( $sql ) ) {
			throw new RuntimeException( 'Native checkout storage unavailable.' );
		}
	}
}

/** Opt-in direct platform wrapper. It never creates or pays an order itself. */
final class MobiShop_Native_Checkout_Safety50 {
	public const NAMESPACE = 'mobishop_native_checkout50';
	private const PAYMENT_HOOK = 'woocommerce_rest_checkout_process_payment_with_context';
	private MobiShop_Native_Checkout_Store50 $store;
	private bool $registered = false;
	private ?array $active = null;
	private ?array $deferred_payment_hook = null;
	private WeakMap $pre_rejections;

	public function __construct( ?MobiShop_Native_Checkout_Store50 $store = null ) {
		$this->store = $store ?? new MobiShop_Native_Checkout_Wpdb50();
		$this->pre_rejections = new WeakMap();
	}

	public function register(): void {
		add_action( 'rest_api_init', array( $this, 'register_routes' ) );
		add_filter( 'rest_request_before_callbacks', array( $this, 'before_callbacks' ), 1000, 3 );
		add_filter( 'rest_request_after_callbacks', array( $this, 'after_callbacks' ), 1000, 3 );
		add_filter( 'rest_dispatch_request', array( $this, 'dispatch' ), 1000, 4 );
		add_filter( 'rest_post_dispatch', array( $this, 'private_headers' ), 1000, 3 );
		add_action( 'woocommerce_before_order_object_save', array( $this, 'before_save' ), 0, 2 );
		add_action( 'woocommerce_after_order_object_save', array( $this, 'after_save' ), 0, 2 );
		add_action( 'woocommerce_checkout_validate_order_before_payment', array( $this, 'validate_final' ), PHP_INT_MAX, 2 );
		add_action( 'woocommerce_store_api_checkout_order_processed', array( $this, 'validate_before_gateway' ), PHP_INT_MAX, 1 );
		if ( did_action( 'woocommerce_blocks_loaded' ) ) {
			$this->register_extension();
		} else {
			add_action( 'woocommerce_blocks_loaded', array( $this, 'register_extension' ) );
		}
	}

	public function register_routes(): void {
		register_rest_route( 'mobishop/v1', '/native-checkout-capabilities', array( 'methods' => 'GET', 'permission_callback' => '__return_true', 'callback' => fn() => $this->response( $this->capabilities() ) ) );
		register_rest_route( 'mobishop/v1', '/customer/checkout-attempts/(?P<key>[A-Za-z0-9._:-]{1,128})', array( 'methods' => 'GET', 'permission_callback' => array( $this, 'authenticate' ), 'callback' => array( $this, 'recover' ) ) );
	}

	public function register_extension(): void {
		if ( $this->registered || ! function_exists( 'woocommerce_store_api_register_endpoint_data' ) || ! class_exists( '\Automattic\WooCommerce\StoreApi\Schemas\V1\CheckoutSchema' ) ) {
			return;
		}
		$result = woocommerce_store_api_register_endpoint_data( array(
			'endpoint' => \Automattic\WooCommerce\StoreApi\Schemas\V1\CheckoutSchema::IDENTIFIER,
			'namespace' => self::NAMESPACE,
			'schema_type' => ARRAY_A,
			'data_callback' => fn(): array => array( 'protocol' => 50, 'enforced' => $this->supported() ),
			'schema_callback' => array( $this, 'extension_schema' ),
		) );
		$this->registered = true === $result;
	}

	public function extension_schema(): array {
		return array(
			'protocol' => array( 'type' => 'integer', 'enum' => array( 50 ), 'context' => array( 'view', 'edit' ) ),
			// Woo recursively validates response-only properties on requests too.
			// Missing enforced is allowed; the response callback still emits bool.
			'enforced' => array( 'type' => array( 'boolean', 'null' ), 'readonly' => true, 'context' => array( 'view' ) ),
			'confirmed' => array( 'type' => 'object', 'context' => array( 'edit' ), 'additionalProperties' => false, 'required' => array( 'total_price', 'currency_code', 'currency_minor_unit' ), 'properties' => array(
				'total_price' => array( 'type' => 'string', 'pattern' => '^[0-9]{1,40}$' ),
				'currency_code' => array( 'type' => 'string', 'pattern' => '^[A-Z]{3}$' ),
				'currency_minor_unit' => array( 'type' => 'integer', 'minimum' => 0, 'maximum' => 8 ),
			) ),
		);
	}

	public function capabilities(): array {
		return array( 'protocol' => 50, 'enforced' => $this->supported(), 'checkout_route' => '/wc/store/v1/checkout', 'recovery_route' => '/mobishop/v1/customer/checkout-attempts/{key}', 'guest_checkout' => false, 'automatic_replay' => false, 'qa_isolation' => false );
	}

	/** A version string alone does not establish that the actual guard exists. */
	private function supported(): bool {
		if ( ! $this->registered || ! MobiShop_Native_Checkout_Wpdb50::key_configured() || ! defined( 'WC_VERSION' ) || version_compare( WC_VERSION, '9.9.0', '<' ) || ! function_exists( 'array_is_list' ) || ! has_action( 'woocommerce_checkout_validate_order_before_payment', array( $this, 'validate_final' ) ) || ! has_action( 'rest_request_before_callbacks', array( $this, 'before_callbacks' ) ) || ! has_action( 'rest_request_after_callbacks', array( $this, 'after_callbacks' ) ) || ! class_exists( '\Automattic\WooCommerce\StoreApi\Utilities\CartTokenUtils' ) || ! $this->pre_dispatch_boundary_supported() ) {
			return false;
		}
		try {
			$class = '\Automattic\WooCommerce\StoreApi\Utilities\OrderController';
			$guard = new ReflectionMethod( $class, 'perform_custom_order_validation' );
			$validation = new ReflectionMethod( $class, 'validate_order_before_payment' );
			$lines = file( $guard->getFileName() );
			$text = implode( '', array_slice( $lines ?: array(), $guard->getStartLine() - 1, $guard->getEndLine() - $guard->getStartLine() + 1 ) );
			$validation_lines = file( $validation->getFileName() );
			$validation_text = implode( '', array_slice( $validation_lines ?: array(), $validation->getStartLine() - 1, $validation->getEndLine() - $validation->getStartLine() + 1 ) );
			return str_contains( $text, "do_action( 'woocommerce_checkout_validate_order_before_payment'" ) && str_contains( $validation_text, '$this->perform_custom_order_validation(' ) && $this->store->ready();
		} catch ( Throwable $error ) {
			return false;
		}
	}

	/** Verify the installed WP boundary, not merely a guessed version number. */
	private function pre_dispatch_boundary_supported(): bool {
		try {
			$read = static function ( string $method ): string {
				$reflection = new ReflectionMethod( 'WP_REST_Server', $method );
				$lines = file( $reflection->getFileName() );
				return implode( '', array_slice( $lines ?: array(), $reflection->getStartLine() - 1, $reflection->getEndLine() - $reflection->getStartLine() + 1 ) );
			};
			$dispatch = $read( 'dispatch' );
			$respond = $read( 'respond_to_request' );
			$validation = strpos( $dispatch, '$request->has_valid_params()' );
			$match = strpos( $dispatch, '$this->respond_to_request(' );
			$before = strpos( $respond, "apply_filters( 'rest_request_before_callbacks'" );
			$permission = strpos( $respond, "call_user_func( \$handler['permission_callback']" );
			$guard = strpos( $respond, 'if ( ! is_wp_error( $response ) )', false === $permission ? 0 : $permission );
			$filter = strpos( $respond, "apply_filters( 'rest_dispatch_request'" );
			$callback = strpos( $respond, "call_user_func( \$handler['callback']" );
			$after = strpos( $respond, "apply_filters( 'rest_request_after_callbacks'" );
			return false !== $validation && false !== $match && $validation < $match && false !== $before && false !== $permission && false !== $guard && false !== $filter && false !== $callback && false !== $after && $before < $permission && $permission < $guard && $guard < $filter && $filter < $callback && $callback < $after;
		} catch ( Throwable $error ) {
			return false;
		}
	}

	/**
	 * WP 6.8 validates/sanitizes before this filter, then skips permission and
	 * dispatch while the result remains WP_Error. Never turn it into Response
	 * here: that would remove WP's callback-blocking condition.
	 */
	public function before_callbacks( $response, array $handler, WP_REST_Request $request ) {
		if ( ! $this->native_json_request( $request ) || ! is_wp_error( $response ) || ! is_callable( $handler['callback'] ?? null ) || ! $this->supported() ) {
			return $response;
		}
		$codes = $response->get_error_codes();
		$data = $response->get_error_data();
		if ( ! $codes || array_diff( $codes, array( 'rest_invalid_param', 'rest_missing_callback_param', 'rest_invalid_json' ) ) || ! is_array( $data ) || ! in_array( $data['status'] ?? null, array( 400, 422 ), true ) ) {
			return $response;
		}
		$customer = $this->identity( $request );
		if ( is_wp_error( $customer ) ) {
			return $response;
		}
		$rejection = $this->pre_dispatch_rejection( $request, $customer );
		$envelope = $rejection->get_data();
		$this->pre_rejections[ $request ] = $rejection;
		return new WP_Error( $envelope['code'], $envelope['message'] ?? 'Review checkout before submitting a new attempt.', array( 'status' => $rejection->get_status() ) + $envelope );
	}

	/** Flatten only our own proof AFTER WP's callback-blocking gate has passed. */
	public function after_callbacks( $response, array $handler, WP_REST_Request $request ) {
		unset( $handler );
		if ( ! isset( $this->pre_rejections[ $request ] ) || ! is_wp_error( $response ) ) {
			return $response;
		}
		$proof = $this->pre_rejections[ $request ];
		$data = $response->get_error_data();
		if ( $response->get_error_codes() !== array( $proof->get_data()['code'] ) || ! is_array( $data ) || ( $data['status'] ?? null ) !== $proof->get_status() ) {
			return $response;
		}
		unset( $this->pre_rejections[ $request ] );
		return $this->no_store( $proof );
	}

	public function authenticate( WP_REST_Request $request ) {
		return is_wp_error( $this->identity( $request ) ) ? new WP_Error( 'mobishop_native_checkout50_unauthorized', 'The customer session is missing or expired.', array( 'status' => 401 ) ) : true;
	}

	/** Also prevent caching of permission failures on our private GET route. */
	public function private_headers( $response, $server, WP_REST_Request $request ) {
		unset( $server );
		$extensions = $request->get_param( 'extensions' );
		$native_post = '/wc/store/v1/checkout' === $request->get_route() && 'POST' === $request->get_method() && is_array( $extensions ) && array_key_exists( self::NAMESPACE, $extensions );
		if ( ( $native_post || preg_match( '~^/mobishop/v1/(?:customer/checkout-attempts/[A-Za-z0-9._:-]{1,128}|native-checkout-capabilities)$~D', $request->get_route() ) ) && $response instanceof WP_REST_Response ) {
			return $this->no_store( $response );
		}
		return $response;
	}

	/** Wrap only explicitly opted-in JSON Native checkout; website unchanged. */
	public function dispatch( $result, WP_REST_Request $request, string $route, array $handler ) {
		$extensions = $request->get_param( 'extensions' );
		if ( '/wc/store/v1/checkout' !== $request->get_route() || 'POST' !== $request->get_method() || ! is_array( $extensions ) || ! array_key_exists( self::NAMESPACE, $extensions ) ) {
			return $result;
		}
		if ( null !== $result || null !== $this->active || ! $this->supported() || ! is_callable( $handler['callback'] ?? null ) ) {
			return $this->error( 'unavailable', 503 );
		}
		$customer = $this->identity( $request );
		if ( is_wp_error( $customer ) ) {
			return $this->error( 'unauthorized', 401 );
		}
		$extension = $extensions[ self::NAMESPACE ];
		$confirmed = is_array( $extension ) ? self::confirmed( $extension['confirmed'] ?? null ) : null;
		$key = (string) $request->get_header( 'Idempotency-Key' );
		if ( ! preg_match( '/^[A-Za-z0-9._:-]{1,128}$/D', $key ) ) {
			return $this->error( 'invalid_contract', 400 ); // No exact key to tombstone.
		}
		if ( ! is_array( $extension ) || 50 !== ( $extension['protocol'] ?? null ) || ! $confirmed ) {
			return $this->pre_dispatch_rejection( $request, $customer );
		}
		try {
			$cart_user = $this->cart_identity( $request, $customer );
			if ( null === $cart_user ) {
				return $this->error( 'cart_ownership', 403 );
			}
			$body = $request->get_json_params();
			if ( ! is_array( $body ) || ( $body['extensions'][ self::NAMESPACE ] ?? null ) !== $extension || ( method_exists( $request, 'get_query_params' ) && $request->get_query_params() ) || ( method_exists( $request, 'get_body_params' ) && $request->get_body_params() ) ) {
				return $this->pre_dispatch_rejection( $request, $customer );
			}
			try {
				$canonical = json_encode( self::canonical( $body ), JSON_UNESCAPED_SLASHES | JSON_UNESCAPED_UNICODE | JSON_THROW_ON_ERROR );
			} catch ( InvalidArgumentException | JsonException $error ) {
				return $this->pre_dispatch_rejection( $request, $customer );
			}
			if ( strlen( $canonical ) > 131072 ) {
				return $this->pre_dispatch_rejection( $request, $customer );
			}
			$buyer = $this->digest( 'buyer', (string) $customer );
			$attempt = $this->digest( 'attempt', $key );
			$cart = $this->digest( 'cart', $cart_user );
			$claim = $this->store->claim( array( 'buyer_scope' => $buyer, 'attempt_hash' => $attempt, 'cart_scope' => $cart, 'payload_hash' => $this->digest( 'payload', $cart . '|' . $canonical ), 'customer_id' => $customer ) );
			if ( isset( $claim['attempt'] ) && 'rejected_before_dispatch' === $claim['attempt']['state'] ) {
				return $this->pre_rejection_response( $claim['attempt'], $customer, $key );
			}
			if ( 'existing' === $claim['result'] ) {
				return $this->recovery_response( $claim['attempt'], $customer, 'unknown', $request );
			}
			if ( 'claimed' !== $claim['result'] ) {
				return $this->error( 'unavailable' === $claim['result'] ? 'storage_unavailable' : 'attempt_conflict', 'unavailable' === $claim['result'] ? 503 : 409 );
			}
			$this->active = array( 'buyer' => $buyer, 'attempt' => $attempt, 'cart' => $cart, 'cart_user' => $cart_user, 'customer' => $customer, 'request' => $request, 'confirmed' => $confirmed, 'order_id' => 0, 'conflict' => false, 'passed' => false, 'safe_rejection' => false, 'after_stock' => false, 'purchased_cart' => null );
			try {
				$response = call_user_func( $handler['callback'], $request );
				if ( ! $this->store->finished( $buyer, $attempt ) ) {
					return $this->error( 'outcome_unknown', 503 );
				}
				return $this->finish( $response );
			} catch ( Throwable $error ) {
				if ( ! $this->store->finished( $buyer, $attempt ) ) {
					return $this->error( 'outcome_unknown', 503 );
				}
				// Only this class's exact pre-payment guard may resolve a rejection.
				if ( $this->active['safe_rejection'] ) {
					return $this->store->settle( $buyer, $attempt, 'rejected_before_payment', '' ) ? $this->error( 'confirmed_total_mismatch', 409 ) : $this->error( 'outcome_unknown', 503 );
				}
				return $this->error( 'outcome_unknown', 503 );
			} finally {
				$this->restore_payment_hook();
				$this->active = null;
			}
		} catch ( Throwable $error ) {
			return $this->error( 'storage_unavailable', 503 );
		}
	}

	/** Metadata only: exceptions from WC_Order::save are not a safe rejection. */
	public function before_save( $order, $data_store = null ): void {
		unset( $data_store );
		if ( ! $this->active || ! $order instanceof WC_Order || 'shop_order' !== $order->get_type() || 'store-api' !== $order->get_created_via() ) {
			return;
		}
		try {
			if ( (int) $order->get_customer_id() !== $this->active['customer'] || ( $this->active['order_id'] && (int) $order->get_id() !== $this->active['order_id'] ) ) {
				$this->active['conflict'] = true;
				return;
			}
			$previous = (string) $order->get_meta( '_mobishop_native_attempt50', true );
			if ( $previous && $previous !== $this->active['attempt'] ) {
				$old = $this->store->find( $this->active['buyer'], $previous );
				if ( 'checkout-draft' !== $order->get_status() || ! $old || 'rejected_before_payment' !== $old['state'] ) {
					$this->active['conflict'] = true;
					return;
				}
			}
			$order->update_meta_data( '_mobishop_native_attempt50', $this->active['attempt'] );
			$order->update_meta_data( '_mobishop_native_buyer50', $this->active['buyer'] );
		} catch ( Throwable $error ) {
			$this->active['conflict'] = true;
		}
	}

	public function after_save( $order, $data_store = null ): void {
		unset( $data_store );
		if ( ! $this->active || ! $order instanceof WC_Order || (int) $order->get_id() <= 0 || (string) $order->get_meta( '_mobishop_native_attempt50', true ) !== $this->active['attempt'] ) {
			return;
		}
		try {
			if ( (int) $order->get_customer_id() !== $this->active['customer'] || ! $this->store->associate( $this->active['buyer'], $this->active['attempt'], (int) $order->get_id() ) ) {
				$this->active['conflict'] = true;
				return;
			}
			$this->active['order_id'] = (int) $order->get_id();
		} catch ( Throwable $error ) {
			$this->active['conflict'] = true;
		}
	}

	/** This verified hook runs BEFORE coupon/stock holds or payment. */
	public function validate_final( $order, $errors ): void {
		unset( $errors );
		if ( ! $this->active ) {
			return;
		}
		$this->active['safe_rejection'] = false;
		try {
			$current = $this->identity( $this->active['request'] );
			$wc = WC();
			$persisted = $order instanceof WC_Order && (int) $order->get_id() > 0 ? wc_get_order( (int) $order->get_id() ) : false;
			if ( is_wp_error( $current ) || $current !== $this->active['customer'] || ! $order instanceof WC_Order || ! $persisted instanceof WC_Order || $this->active['conflict'] || (int) $order->get_id() !== $this->active['order_id'] || (int) $order->get_customer_id() !== $current || (int) $persisted->get_customer_id() !== $current || (string) $persisted->get_meta( '_mobishop_native_attempt50', true ) !== $this->active['attempt'] || (string) $persisted->get_meta( '_mobishop_native_buyer50', true ) !== $this->active['buyer'] || (string) $order->get_meta( '_mobishop_native_attempt50', true ) !== $this->active['attempt'] || $this->cart_identity( $this->active['request'], $current ) !== $this->active['cart_user'] || ! $this->store->owns_cart( $this->active['cart'], $this->active['buyer'] ) || ! $wc || ! $wc->session || (string) $wc->session->get_customer_id() !== $this->active['cart_user'] || ! $wc->customer || (int) $wc->customer->get_id() !== $current ) {
				throw new RuntimeException( 'Native checkout ownership was not established.' );
			}
			$expected = $this->active['confirmed'];
			$actual = self::decimal_to_minor( $order->get_total( 'edit' ), wc_get_price_decimals() );
			if ( null === $actual || $actual !== $expected['total_price'] || $order->get_currency() !== $expected['currency_code'] || wc_get_price_decimals() !== $expected['currency_minor_unit'] ) {
				$this->active['safe_rejection'] = ! $this->active['after_stock'];
				throw new \Automattic\WooCommerce\StoreApi\Exceptions\RouteException( 'mobishop_native_checkout50_confirmed_total_mismatch', 'Review the current order total before confirming again.', 409 );
			}
			$fingerprint = $this->cart_fingerprint( $wc->cart ?? null );
			if ( null === $fingerprint || ( null !== $this->active['purchased_cart'] && ! hash_equals( $this->active['purchased_cart'], $fingerprint ) ) ) {
				throw new RuntimeException( 'The purchased Native cart could not be established.' );
			}
			// Immutable within this dispatch: later validation cannot bless a new cart.
			$this->active['purchased_cart'] ??= $fingerprint;
			if ( ! $this->store->passed( $this->active['buyer'], $this->active['attempt'] ) ) {
				throw new RuntimeException( 'Native checkout guard result was not persisted.' );
			}
			$this->active['passed'] = true;
		} catch ( \Automattic\WooCommerce\StoreApi\Exceptions\RouteException $error ) {
			throw $error;
		} catch ( Throwable $error ) {
			throw new \Automattic\WooCommerce\StoreApi\Exceptions\RouteException( 'mobishop_native_checkout50_outcome_unknown', 'Checkout safety could not be established. Recover this attempt before retrying.', 503 );
		}
	}

	/** Detect normal order-processed extensions changing money after validation. */
	public function validate_before_gateway( $order ): void {
		if ( ! $this->active ) {
			return;
		}
		$this->active['after_stock'] = true;
		$this->validate_final( $order, new WP_Error() );
		$this->defer_online_payment( $order );
	}

	/**
	 * Empty Native payment data cannot supply website card fields or tokens.
	 * Keep Woo's validated, reserved pending order and let its own order-pay
	 * page collect those fields. Core offline methods retain their normal flow.
	 */
	private function defer_online_payment( $order ): void {
		$request = $this->active['request'];
		$method = $request->get_param( 'payment_method' );
		if ( ! is_string( $method ) || '' === $method || in_array( $method, array( 'cod', 'bacs', 'cheque' ), true ) || array() !== $request->get_param( 'payment_data' ) || '0' === $this->active['confirmed']['total_price'] ) {
			return;
		}
		if ( $this->deferred_payment_hook || ! class_exists( 'WP_Hook' ) || ! $order instanceof WC_Order || ! is_callable( array( $order, 'get_payment_method' ) ) || $method !== $order->get_payment_method() || 'pending' !== $order->get_status() || ! $order->needs_payment() || $order->is_paid() ) {
			throw new RuntimeException( 'Native website payment hand-off could not be established.' );
		}
		$original = $GLOBALS['wp_filter'][ self::PAYMENT_HOOK ] ?? null;
		if ( null !== $original && ! $original instanceof WP_Hook ) {
			throw new RuntimeException( 'Native payment hook is unavailable.' );
		}
		$replacement = new WP_Hook();
		$replacement->add_filter( self::PAYMENT_HOOK, array( $this, 'handoff_payment' ), PHP_INT_MIN, 2 );
		$this->deferred_payment_hook = array( 'original' => $original, 'replacement' => $replacement, 'method' => $method, 'used' => false );
		// Setting a successful result at an early priority alone is insufficient:
		// third-party handlers need not respect it and could still charge. Replace
		// this one hook only until this exact guarded dispatch unwinds in finally.
		$GLOBALS['wp_filter'][ self::PAYMENT_HOOK ] = $replacement;
	}

	/** A successful hand-off is not a captured payment or a paid order. */
	public function handoff_payment( $context, &$result ): void {
		if ( ! $this->active || ! $this->deferred_payment_hook || $this->deferred_payment_hook['used'] || ! $this->active['passed'] || ! $this->active['after_stock'] || ( $GLOBALS['wp_filter'][ self::PAYMENT_HOOK ] ?? null ) !== $this->deferred_payment_hook['replacement'] || ! $context instanceof \Automattic\WooCommerce\StoreApi\Payments\PaymentContext || ! $result instanceof \Automattic\WooCommerce\StoreApi\Payments\PaymentResult || '' !== $result->status || $context->payment_method !== $this->deferred_payment_hook['method'] || array() !== $context->payment_data ) {
			throw new RuntimeException( 'Native payment context could not be established.' );
		}
		$this->validate_payment_hook();
		$this->deferred_payment_hook['used'] = true;
		$order = $context->order;
		$this->validate_final( $order, new WP_Error() );
		$persisted = wc_get_order( $this->active['order_id'] );
		foreach ( array( $order, $persisted ) as $candidate ) {
			if ( ! $candidate instanceof WC_Order || ! is_callable( array( $candidate, 'get_payment_method' ) ) || $candidate->get_payment_method() !== $this->deferred_payment_hook['method'] || 'pending' !== $candidate->get_status() || ! $candidate->needs_payment() || $candidate->is_paid() || self::decimal_to_minor( $candidate->get_total( 'edit' ), wc_get_price_decimals() ) !== $this->active['confirmed']['total_price'] || $candidate->get_currency() !== $this->active['confirmed']['currency_code'] ) {
				throw new RuntimeException( 'Native pending payment order could not be established.' );
			}
		}
		$gateway = $context->get_payment_method_instance();
		if ( ! $gateway instanceof WC_Payment_Gateway || $gateway->id !== $this->deferred_payment_hook['method'] ) {
			throw new RuntimeException( 'Native selected payment method is unavailable.' );
		}
		$this->validate_payment_hook();
		// Keep this sentinel installed: a repeated action must fail on used=true.
		// Removing callbacks while WP_Hook iterates cannot suppress a same-priority
		// callback already captured by its foreach, so reject added handlers instead.
		// finish() emits the existing pending receipt. The owned order endpoint
		// separately supplies a validated same-origin order-pay URL to the app.
		$result->set_status( 'success' );
	}

	private function validate_payment_hook(): void {
		$hook = $this->deferred_payment_hook['replacement'];
		$callbacks = $hook->callbacks;
		$rows = isset( $callbacks[ PHP_INT_MIN ] ) && is_array( $callbacks[ PHP_INT_MIN ] ) ? array_values( $callbacks[ PHP_INT_MIN ] ) : array();
		if ( ( $GLOBALS['wp_filter'][ self::PAYMENT_HOOK ] ?? null ) !== $hook || array( PHP_INT_MIN ) !== array_keys( $callbacks ) || 1 !== count( $rows ) || ( $rows[0]['function'] ?? null ) !== array( $this, 'handoff_payment' ) || 2 !== ( $rows[0]['accepted_args'] ?? null ) ) {
			throw new RuntimeException( 'Native payment hook changed during hand-off.' );
		}
	}

	private function restore_payment_hook(): void {
		if ( null === $this->deferred_payment_hook ) {
			return;
		}
		if ( null === $this->deferred_payment_hook['original'] ) {
			unset( $GLOBALS['wp_filter'][ self::PAYMENT_HOOK ] );
		} else {
			$GLOBALS['wp_filter'][ self::PAYMENT_HOOK ] = $this->deferred_payment_hook['original'];
		}
		$this->deferred_payment_hook = null;
	}

	public function recover( WP_REST_Request $request ) {
		$customer = $this->identity( $request );
		if ( is_wp_error( $customer ) ) {
			return $this->error( 'unauthorized', 401 );
		}
		if ( ! $this->supported() || ! preg_match( '/^[A-Za-z0-9._:-]{1,128}$/D', (string) $request->get_param( 'key' ) ) ) {
			return $this->error( 'unavailable', 503 );
		}
		try {
			$row = $this->store->find( $this->digest( 'buyer', (string) $customer ), $this->digest( 'attempt', (string) $request->get_param( 'key' ) ) );
			// Missing is never a permission to submit again, including expired auth.
			return $row ? $this->recovery_response( $row, $customer, 'unknown', $request ) : $this->response( array( 'state' => 'unknown', 'automatic_replay' => false ), 404 );
		} catch ( Throwable $error ) {
			return $this->error( 'storage_unavailable', 503 );
		}
	}

	private function finish( $response ) {
		if ( $this->active['safe_rejection'] ) {
			return $this->store->settle( $this->active['buyer'], $this->active['attempt'], 'rejected_before_payment', '' ) ? $this->error( 'confirmed_total_mismatch', 409 ) : $this->error( 'outcome_unknown', 503 );
		}
		$response = rest_ensure_response( $response );
		$data = $response instanceof WP_REST_Response ? $response->get_data() : null;
		$payment = is_array( $data ) ? ( $data['payment_result']['payment_status'] ?? '' ) : '';
		if ( ! $this->active['passed'] || ! is_string( $this->active['purchased_cart'] ) || ! is_array( $data ) || (int) ( $data['order_id'] ?? 0 ) !== $this->active['order_id'] || 200 !== $response->get_status() || 'success' !== $payment ) {
			return $this->error( 'outcome_unknown', 503 );
		}
		$row = $this->store->find( $this->active['buyer'], $this->active['attempt'] );
		$current = $this->identity( $this->active['request'] );
		$order = is_array( $row ) && (int) ( $row['order_id'] ?? 0 ) > 0 ? wc_get_order( (int) $row['order_id'] ) : false;
		$wc = WC();
		// A successful gateway hand-off may leave a real order awaiting browser
		// payment. Accept only that exact core status and Woo's unpaid predicate.
		// A pending/failed gateway envelope itself is still ambiguous above.
		$awaiting_payment = $order instanceof WC_Order && 'pending' === $order->get_status()
			&& 'pending' === ( $data['status'] ?? null )
			&& is_callable( array( $order, 'needs_payment' ) ) && $order->needs_payment()
			&& is_callable( array( $order, 'is_paid' ) ) && ! $order->is_paid();
		// Recheck the exact original subject and durable order proof before mutating
		// any cart. A successful gateway envelope alone never authorizes clearing it.
		if ( is_wp_error( $current ) || $current !== $this->active['customer'] || $this->active['conflict'] || ! is_array( $row ) || 'in_progress' !== ( $row['state'] ?? '' ) || (int) ( $row['customer_id'] ?? 0 ) !== $current || (int) ( $row['order_id'] ?? 0 ) !== $this->active['order_id'] || ( $row['buyer_scope'] ?? '' ) !== $this->active['buyer'] || ( $row['attempt_hash'] ?? '' ) !== $this->active['attempt'] || ( $row['cart_scope'] ?? '' ) !== $this->active['cart'] || 1 !== (int) ( $row['guard_passed'] ?? 0 ) || 1 !== (int) ( $row['dispatch_finished'] ?? 0 ) || ! $order instanceof WC_Order || (int) $order->get_customer_id() !== $current || (string) $order->get_meta( '_mobishop_native_attempt50', true ) !== $this->active['attempt'] || (string) $order->get_meta( '_mobishop_native_buyer50', true ) !== $this->active['buyer'] || ( ! $awaiting_payment && ! in_array( $order->get_status(), array( 'processing', 'completed', 'on-hold' ), true ) ) || $this->cart_identity( $this->active['request'], $current, false ) !== $this->active['cart_user'] || ! hash_equals( $this->active['cart'], $this->digest( 'cart', $this->active['cart_user'] ) ) || ! $this->store->owns_cart( $this->active['cart'], $this->active['buyer'] ) || ! $wc || ! $wc->session || (string) $wc->session->get_customer_id() !== $this->active['cart_user'] || ! is_callable( array( $wc->session, 'save_data' ) ) || ! $wc->customer || (int) $wc->customer->get_id() !== $current || ! $wc->cart || ! is_callable( array( $wc->cart, 'is_empty' ) ) ) {
			return $this->error( 'outcome_unknown', 503 );
		}
		if ( ! $wc->cart->is_empty() ) {
			$fingerprint = $this->cart_fingerprint( $wc->cart );
			if ( null === $fingerprint || ! hash_equals( $this->active['purchased_cart'], $fingerprint ) || $this->cart_identity( $this->active['request'], $current ) !== $this->active['cart_user'] || ! is_callable( array( $wc->cart, 'empty_cart' ) ) ) {
				return $this->error( 'outcome_unknown', 503 );
			}
			// Store API success need not visit Woo's order-received page. Complete its
			// genuine cart lifecycle only for the exact cart purchased by this attempt.
			$wc->cart->empty_cart();
		}
		if ( ! $wc->cart->is_empty() ) {
			return $this->error( 'outcome_unknown', 503 );
		}
		$wc->session->save_data(); // Also persist a cart already emptied by core.
		$recovered = $this->recovery_response( $row, $this->active['customer'], $awaiting_payment ? 'pending' : 'success', $this->active['request'] );
		// Preserve core's authenticated response, but never persist its private data.
		if ( 200 !== $recovered->get_status() || 'order_created' !== ( $recovered->get_data()['state'] ?? '' ) || $recovered->get_data()['checkout_locked'] ) {
			return $recovered;
		}
		// Do not label gateway hand-off as captured payment or expose an
		// arbitrary gateway URL. The owned order endpoint supplies continuation.
		return $awaiting_payment ? $recovered : $this->no_store( $response );
	}

	/** Request-local purchased items only; never serialize product objects or PII. */
	private function cart_fingerprint( $cart ): ?string {
		if ( ! is_object( $cart ) || ! is_callable( array( $cart, 'get_cart' ) ) ) {
			return null;
		}
		$items = $cart->get_cart();
		if ( ! is_array( $items ) || ! $items ) {
			return null;
		}
		$normalized = array();
		foreach ( $items as $key => $item ) {
			if ( ! is_string( $key ) || ! $key || ! is_array( $item ) || ! is_array( $item['variation'] ?? null ) ) {
				return null;
			}
			$line = array();
			foreach ( array( 'product_id', 'variation_id' ) as $field ) {
				$value = $item[ $field ] ?? null;
				if ( ( ! is_int( $value ) && ! is_string( $value ) ) || ! preg_match( '/^[0-9]{1,18}$/D', (string) $value ) || ( 'product_id' === $field && 0 === (int) $value ) ) {
					return null;
				}
				$line[ $field ] = ltrim( (string) $value, '0' ) ?: '0';
			}
			$variation = $item['variation'];
			foreach ( $variation as $attribute => $value ) {
				if ( ! is_string( $attribute ) || ! is_string( $value ) ) {
					return null;
				}
			}
			ksort( $variation, SORT_STRING );
			$line['variation'] = $variation;
			foreach ( array( 'quantity', 'line_subtotal', 'line_subtotal_tax', 'line_total', 'line_tax' ) as $field ) {
				$value = $item[ $field ] ?? null;
				$number = self::cart_number( $value );
				if ( null === $number || ( 'quantity' === $field && ( (float) $number <= 0 || ! is_finite( (float) $number ) ) ) ) {
					return null;
				}
				$line[ $field ] = $number;
			}
			$normalized[ $key ] = $line;
		}
		ksort( $normalized, SORT_STRING );
		return hash( 'sha256', json_encode( $normalized, JSON_UNESCAPED_SLASHES | JSON_UNESCAPED_UNICODE | JSON_THROW_ON_ERROR ) );
	}

	/** Preserve real quantity/price precision, independent of currency rounding. */
	private static function cart_number( $value ): ?string {
		if ( is_float( $value ) ) {
			if ( ! is_finite( $value ) ) {
				return null;
			}
			$value = sprintf( '%.17g', $value );
		}
		if ( ( ! is_int( $value ) && ! is_string( $value ) ) || strlen( (string) $value ) > 128 || ! preg_match( '/^(-?)([0-9]+)(?:\.([0-9]+))?(?:[eE]([+-]?[0-9]{1,3}))?$/D', (string) $value, $parts ) ) {
			return null;
		}
		$digits = $parts[2] . ( $parts[3] ?? '' );
		$point = strlen( $parts[2] ) + (int) ( $parts[4] ?? 0 );
		$decimal = $point <= 0 ? '0.' . str_repeat( '0', -$point ) . $digits : ( $point >= strlen( $digits ) ? $digits . str_repeat( '0', $point - strlen( $digits ) ) : substr( $digits, 0, $point ) . '.' . substr( $digits, $point ) );
		$whole = explode( '.', $decimal, 2 );
		$number = ( ltrim( $whole[0], '0' ) ?: '0' ) . ( isset( $whole[1] ) && '' !== rtrim( $whole[1], '0' ) ? '.' . rtrim( $whole[1], '0' ) : '' );
		return ( '-' === $parts[1] && '0' !== $number ? '-' : '' ) . $number;
	}

	private function recovery_response( array $row, int $customer, string $observed_payment = 'unknown', ?WP_REST_Request $request = null ): WP_REST_Response {
		if ( (int) $row['customer_id'] !== $customer ) {
			return $this->response( array( 'state' => 'unknown', 'automatic_replay' => false ), 404 );
		}
		if ( 'rejected_before_dispatch' === $row['state'] ) {
			$key = $request ? ( 'GET' === $request->get_method() ? (string) $request->get_param( 'key' ) : (string) $request->get_header( 'Idempotency-Key' ) ) : '';
			return $this->pre_rejection_response( $row, $customer, $key );
		}
		if ( 'rejected_before_payment' === $row['state'] ) {
			return $this->response( array( 'state' => 'rejected_before_payment', 'code' => 'mobishop_native_checkout50_rejected_before_payment', 'automatic_replay' => false ), 409 );
		}
		$order = (int) $row['order_id'] > 0 ? wc_get_order( (int) $row['order_id'] ) : false;
		if ( ! $order instanceof WC_Order || (int) $order->get_customer_id() !== $customer || (string) $order->get_meta( '_mobishop_native_attempt50', true ) !== $row['attempt_hash'] || (string) $order->get_meta( '_mobishop_native_buyer50', true ) !== $row['buyer_scope'] || 1 !== (int) $row['guard_passed'] ) {
			return $this->response( array( 'state' => 'unknown', 'automatic_replay' => false ), 202 );
		}
		$status = $order->get_status();
		$verified_pending = 'pending' === $observed_payment && 'pending' === $status
			&& 1 === (int) ( $row['dispatch_finished'] ?? 0 )
			&& is_callable( array( $order, 'needs_payment' ) ) && $order->needs_payment()
			&& is_callable( array( $order, 'is_paid' ) ) && ! $order->is_paid();
		if ( 'order_created' !== $row['state'] && ! $verified_pending && ! in_array( $status, array( 'processing', 'completed', 'on-hold' ), true ) ) {
			return $this->response( array( 'state' => 'in_progress', 'automatic_replay' => false ), 202 );
		}
		$total = self::decimal_to_minor( $order->get_total( 'edit' ), wc_get_price_decimals() );
		if ( null === $total || ! preg_match( '/^[a-z0-9-]{1,64}$/D', $status ) ) {
			return $this->response( array( 'state' => 'unknown', 'automatic_replay' => false ), 503 );
		}
		$payment = 'order_created' === $row['state'] ? $row['payment_status'] : $observed_payment;
		// The immutable receipt records hand-off, not subsequent capture. If the
		// order has since changed, let the owned order endpoint confirm payment
		// without emitting an inconsistent pending + completed/cancelled receipt.
		if ( 'pending' === $payment && 'pending' !== $status ) {
			$payment = 'unknown';
		}
		$locked = 'order_created' !== $row['state'];
		if ( $locked && 1 === (int) ( $row['dispatch_finished'] ?? 0 ) && $request ) {
			$cart_user = $this->cart_identity( $request, $customer, false );
			if ( $cart_user && hash_equals( $row['cart_scope'], $this->digest( 'cart', $cart_user ) ) && $this->store->owns_cart( $row['cart_scope'], $row['buyer_scope'] ) && $this->store->cart_empty( $cart_user ) ) {
				$locked = false;
			}
		}
		if ( 'order_created' !== $row['state'] && ! $locked && ! $this->store->settle( $row['buyer_scope'], $row['attempt_hash'], 'order_created', $payment ) ) {
			return $this->response( array( 'state' => 'unknown', 'automatic_replay' => false ), 503 );
		}
		return $this->response( array( 'state' => 'order_created', 'checkout_locked' => $locked, 'automatic_replay' => false, 'payment_status' => $payment, 'order' => array( 'id' => (int) $order->get_id(), 'status' => $status, 'total_price' => $total, 'currency_code' => $order->get_currency(), 'currency_minor_unit' => wc_get_price_decimals() ) ) );
	}

	/** Only reliable JSON opt-in, never inferred from a malformed body or query. */
	private function native_json_request( WP_REST_Request $request ): bool {
		$body = $request->get_json_params();
		return '/wc/store/v1/checkout' === $request->get_route() && 'POST' === $request->get_method() && is_array( $body ) && is_array( $body['extensions'] ?? null ) && array_key_exists( self::NAMESPACE, $body['extensions'] );
	}

	/** Persist non-dispatch proof atomically before telling Native to reconfirm. */
	private function pre_dispatch_rejection( WP_REST_Request $request, int $customer ): WP_REST_Response {
		$key = (string) $request->get_header( 'Idempotency-Key' );
		if ( ! $this->native_json_request( $request ) || ! preg_match( '/^[A-Za-z0-9._:-]{1,128}$/D', $key ) ) {
			return $this->error( 'invalid_contract', 400 );
		}
		if ( null !== $this->active ) {
			return $this->error( 'outcome_unknown', 503 );
		}
		try {
			$buyer = $this->digest( 'buyer', (string) $customer );
			$attempt = $this->digest( 'attempt', $key );
			$claim = $this->store->reject_before_dispatch( array( 'buyer_scope' => $buyer, 'attempt_hash' => $attempt, 'customer_id' => $customer, 'payload_hash' => $this->digest( 'pre-dispatch', $attempt ), 'cart_scope' => $this->digest( 'no-cart-dispatched', $attempt ) ) );
			if ( in_array( $claim['result'], array( 'rejected', 'existing' ), true ) && isset( $claim['attempt'] ) ) {
				return $this->pre_rejection_response( $claim['attempt'], $customer, $key );
			}
			return $this->error( 'blocked' === $claim['result'] ? 'attempt_conflict' : 'storage_unavailable', 'blocked' === $claim['result'] ? 409 : 503 );
		} catch ( Throwable $error ) {
			return $this->error( 'storage_unavailable', 503 );
		}
	}

	/** Validate every persisted proof field; existing unknown rows cannot qualify. */
	private function pre_rejection_response( array $row, int $customer, string $key ): WP_REST_Response {
		if ( ! preg_match( '/^[A-Za-z0-9._:-]{1,128}$/D', $key ) || (int) ( $row['customer_id'] ?? 0 ) !== $customer || ! hash_equals( $this->digest( 'buyer', (string) $customer ), (string) ( $row['buyer_scope'] ?? '' ) ) || ! hash_equals( $this->digest( 'attempt', $key ), (string) ( $row['attempt_hash'] ?? '' ) ) || 'rejected_before_dispatch' !== ( $row['state'] ?? '' ) || 0 !== (int) ( $row['order_id'] ?? -1 ) || 0 !== (int) ( $row['guard_passed'] ?? -1 ) || 1 !== (int) ( $row['dispatch_finished'] ?? 0 ) || ! hash_equals( $this->digest( 'pre-dispatch', $row['attempt_hash'] ), (string) ( $row['payload_hash'] ?? '' ) ) || ! hash_equals( $this->digest( 'no-cart-dispatched', $row['attempt_hash'] ), (string) ( $row['cart_scope'] ?? '' ) ) ) {
			return $this->error( 'outcome_unknown', 503 );
		}
		return $this->response( array( 'code' => 'mobishop_native_checkout50_rejected_before_dispatch', 'state' => 'rejected_before_dispatch', 'checkout_dispatched' => false, 'attempt_key' => $key, 'customer_id' => $customer, 'automatic_replay' => false ), 409 );
	}

	private function identity( WP_REST_Request $request ) {
		if ( ! class_exists( 'MobiShop_Customer_Auth_Endpoint' ) || ! function_exists( 'wp_is_using_https' ) || ! wp_is_using_https() ) {
			return new WP_Error( 'mobishop_native_checkout50_unauthorized', 'The customer session is missing or expired.', array( 'status' => 401 ) );
		}
		$context = ( new MobiShop_Customer_Auth_Endpoint() )->session_context_from_request( $request );
		if ( is_wp_error( $context ) || ! is_array( $context ) || (int) ( $context['user_id'] ?? 0 ) <= 0 || (int) $context['user_id'] !== get_current_user_id() ) {
			return new WP_Error( 'mobishop_native_checkout50_unauthorized', 'The customer session is missing or expired.', array( 'status' => 401 ) );
		}
		return (int) $context['user_id'];
	}

	private function cart_identity( WP_REST_Request $request, int $customer, bool $inspect_stored = true ): ?string {
		$token = (string) $request->get_header( 'Cart-Token' );
		$class = '\Automattic\WooCommerce\StoreApi\Utilities\CartTokenUtils';
		if ( strlen( $token ) > 4096 || ! $class::validate_cart_token( $token ) ) {
			return null;
		}
		$payload = $class::get_cart_token_payload( $token );
		$user = (string) ( $payload['user_id'] ?? '' );
		// Woo 10.9.4 uses wc_rand_hash( 't_', 30 ): prefix plus 30 lower-case
		// hex characters, not 32. Keep previously accepted IDs for persisted
		// carts; none of these formats substitutes for the ownership checks.
		if ( 'store-api' !== ( $payload['iss'] ?? '' ) || (int) ( $payload['exp'] ?? 0 ) <= time() || ! preg_match( '/^(?:[1-9][0-9]{0,17}|t_[a-f0-9]{30}|(?:t_)?[a-f0-9]{32})$/D', $user ) ) {
			return null;
		}
		if ( ctype_digit( $user ) && (string) $customer !== $user ) {
			return null;
		}
		if ( ! $inspect_stored ) {
			return $user;
		}
		$stored = $this->store->cart_customer( $user );
		return null !== $stored && ( 0 === $stored || $customer === $stored ) ? $user : null;
	}

	private function digest( string $domain, string $value ): string {
		// Installation key and table prefix are stable; auth salts and public
		// origin/subdirectory changes MUST NOT namespace around an old blocker.
		return hash_hmac( 'sha256', 'mobishop-native-checkout50|' . $domain . '|' . $value, MOBISHOP_NATIVE_CHECKOUT50_HMAC_KEY );
	}

	/** No float/coercion/int conversion: exact arbitrary-sized minor-unit string. */
	public static function confirmed( $value ): ?array {
		if ( ! is_array( $value ) || count( $value ) !== 3 || ! is_string( $value['total_price'] ?? null ) || ! preg_match( '/^[0-9]{1,40}$/D', $value['total_price'] ) || ! is_string( $value['currency_code'] ?? null ) || ! preg_match( '/^[A-Z]{3}$/D', $value['currency_code'] ) || ! is_int( $value['currency_minor_unit'] ?? null ) || $value['currency_minor_unit'] < 0 || $value['currency_minor_unit'] > 8 ) {
			return null;
		}
		$value['total_price'] = ltrim( $value['total_price'], '0' ) ?: '0';
		return $value;
	}

	public static function decimal_to_minor( $value, int $minor ): ?string {
		if ( ! is_string( $value ) || $minor < 0 || $minor > 8 || ! preg_match( '/^([0-9]{1,40})(?:\.([0-9]{1,40}))?$/D', $value, $match ) ) {
			return null;
		}
		$fraction = $match[2] ?? '';
		if ( strlen( $fraction ) > $minor && '' !== trim( substr( $fraction, $minor ), '0' ) ) {
			return null;
		}
		$digits = $match[1] . str_pad( substr( $fraction, 0, $minor ), $minor, '0' );
		return ltrim( $digits, '0' ) ?: '0';
	}

	private static function canonical( $value, int $depth = 0 ) {
		if ( $depth > 20 || is_float( $value ) || is_object( $value ) || is_resource( $value ) ) {
			throw new InvalidArgumentException( 'Invalid Native checkout JSON.' );
		}
		if ( ! is_array( $value ) ) {
			return $value;
		}
		if ( ! array_is_list( $value ) ) {
			ksort( $value, SORT_STRING );
		}
		foreach ( $value as $key => $item ) {
			$value[ $key ] = self::canonical( $item, $depth + 1 );
		}
		return $value;
	}

	private function error( string $code, int $status ): WP_REST_Response {
		return $this->response( array( 'code' => 'mobishop_native_checkout50_' . $code, 'message' => 'Checkout requires a verified safety contract or recovery of the existing attempt.', 'data' => array( 'status' => $status, 'automatic_replay' => false ) ), $status );
	}

	private function response( array $data, int $status = 200 ): WP_REST_Response {
		$data['protocol'] = 50;
		return $this->no_store( new WP_REST_Response( $data, $status ) );
	}

	private function no_store( WP_REST_Response $response ): WP_REST_Response {
		$response->header( 'Cache-Control', 'no-store, no-cache, must-revalidate, max-age=0' );
		$response->header( 'Pragma', 'no-cache' );
		return $response;
	}
