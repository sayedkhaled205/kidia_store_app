<?php
/**
 * Explicit staging-only nonpaid QA order guard. NOT bootstrapped or enabled.
 *
 * This guards ONE administrator-approved fictitious customer and fixture, not
 * arbitrary clients. It does not create a customer/product/order, install an
 * ERP module, alter a gateway, bypass licensing, or certify third-party hooks.
 * A fresh verifier of installed ERP/email/fulfilment guards is REQUIRED before
 * preflight can pass. Merely supplying config, run_id or QA JSON never enables
 * checkout. Core Store API plus Native Safety50 remain the checkout path.
 *
 * @package MobiShop
 */
defined( 'ABSPATH' ) || exit;

final class MobiShop_Native_Qa_Isolation51 {
	public const NAMESPACE = 'mobishop_native_qa51';
	public const MARKER = '_mobishop_native_qa51';
	private array $config;
	private $verifier;
	private ?array $active = null;
	private bool $registered = false;
	private bool $extension_registered = false;
	private array $emails = array();
	/** @var array<int,self> Explicitly registered guards; never request flags. */
	private static array $registered_guards = array();

	/** Verifier is server-owned; never obtained from a request/option/client. */
	public function __construct( array $server_config = array(), ?callable $installed_runtime_verifier = null ) {
		$this->config = $server_config;
		$this->verifier = $installed_runtime_verifier;
	}

	/** Explicit activation only. Keep suppression loaded for historical QA IDs. */
	public function register(): void {
		add_filter( 'rest_dispatch_request', array( $this, 'preflight' ), 900, 4 );
		add_filter( 'rest_post_dispatch', array( $this, 'finish_request' ), PHP_INT_MAX, 3 );
		add_action( 'woocommerce_before_order_object_save', array( $this, 'mark_before_first_save' ), -1000, 2 );
		add_action( 'woocommerce_checkout_validate_order_before_payment', array( $this, 'validate_nonpaid_order' ), 999999, 2 );
		add_action( 'woocommerce_store_api_checkout_order_processed', array( $this, 'validate_nonpaid_order' ), 999999, 1 );
		add_filter( 'woocommerce_can_reduce_order_stock', array( $this, 'allow_stock_reduction' ), PHP_INT_MAX, 2 );
		add_filter( 'woocommerce_webhook_should_deliver', array( $this, 'allow_webhook' ), PHP_INT_MAX, 3 );
		add_action( 'woocommerce_init', array( $this, 'register_email_filters' ), PHP_INT_MAX );
		if ( did_action( 'woocommerce_blocks_loaded' ) ) {
			$this->register_extension();
		} else {
			add_action( 'woocommerce_blocks_loaded', array( $this, 'register_extension' ) );
		}
		$this->registered = true;
		self::$registered_guards[ spl_object_id( $this ) ] = $this;
	}

	public function register_extension(): void {
		if ( $this->extension_registered || ! function_exists( 'woocommerce_store_api_register_endpoint_data' ) || ! class_exists( '\\Automattic\\WooCommerce\\StoreApi\\Schemas\\V1\\CheckoutSchema' ) ) {
			return;
		}
		$this->extension_registered = true === woocommerce_store_api_register_endpoint_data( array(
			'endpoint' => \Automattic\WooCommerce\StoreApi\Schemas\V1\CheckoutSchema::IDENTIFIER,
			'namespace' => self::NAMESPACE,
			'schema_type' => ARRAY_A,
			'data_callback' => fn(): array => array( 'protocol' => 51, 'qa_isolation' => $this->ready() ),
			'schema_callback' => fn(): array => array(
				'protocol' => array( 'type' => 'integer', 'enum' => array( 51 ), 'context' => array( 'edit', 'view' ) ),
				'run' => array( 'type' => 'string', 'pattern' => '^[a-f0-9]{32}$', 'context' => array( 'edit' ) ),
				'qa_isolation' => array( 'type' => array( 'boolean', 'null' ), 'readonly' => true, 'context' => array( 'view' ) ),
			),
		) );
	}

	/** Enumerate actual Woo email IDs, not a guessed list of standard emails. */
	public function register_email_filters(): void {
		$wc = WC();
		if ( ! $wc || ! is_callable( array( $wc, 'mailer' ) ) ) {
			return;
		}
		foreach ( $wc->mailer()->get_emails() as $email ) {
			$id = $email->id ?? '';
			if ( ! is_string( $id ) || ! preg_match( '/^[a-zA-Z0-9_-]{1,100}$/D', $id ) ) {
				continue;
			}
			$this->emails[] = $id;
			add_filter( 'woocommerce_email_enabled_' . $id, array( $this, 'allow_email' ), PHP_INT_MAX, 3 );
		}
	}

	public function capabilities(): array {
		return array( 'protocol' => 51, 'qa_isolation' => $this->ready(), 'gateway_payment' => false, 'ordinary_checkout_changed' => false );
	}

	/** Fresh installed-state proof must be generated by an audited server probe. */
	public function ready(): bool {
		if ( ! $this->registered || ! $this->extension_registered || ! $this->valid_configuration() || ! $this->verifier || ! $this->environment_matches() || ! $this->fixture_matches() || ! $this->customer_matches() || ! $this->emails ) {
			return false;
		}
		try {
			$proof = ( $this->verifier )( $this->public_scope() );
			if ( ! is_array( $proof ) || ( $proof['scope_sha256'] ?? null ) !== hash( 'sha256', self::canonical_scope( $this->config ) ) || ! is_int( $proof['verified_at'] ?? null ) || $proof['verified_at'] > time() || $proof['verified_at'] < time() - 60 ) {
				return false;
			}
			foreach ( array( 'safety50', 'first_draft_hook', 'zero_payment_path', 'email_guards', 'order_webhook_guard', 'erp_poll_guard', 'erp_webhook_guard', 'third_party_fulfilment_inventory' ) as $requirement ) {
				if ( ! is_string( $proof[ $requirement ] ?? null ) || ! preg_match( '/^[a-f0-9]{64}$/D', $proof[ $requirement ] ) ) {
					return false;
				}
			}
			return true;
		} catch ( Throwable $error ) {
			return false;
		}
	}

	/** Preflight never invokes the core callback or mutates a customer/cart. */
	public function preflight( $result, WP_REST_Request $request, string $route, array $handler ) {
		unset( $route, $handler );
		if ( '/wc/store/v1/checkout' !== $request->get_route() || 'POST' !== $request->get_method() ) {
			return $result;
		}
		$extensions = $request->get_param( 'extensions' );
		$opted_in = is_array( $extensions ) && array_key_exists( self::NAMESPACE, $extensions );
		$customer = $this->authenticated_customer( $request );
		$owned_customer = $this->valid_configuration() && $customer === $this->config['customer_id'];
		if ( ! $opted_in && ! $owned_customer ) {
			return $result; // Ordinary website/customer flow unchanged.
		}
		if ( null !== $result || $this->active || ! $this->ready() ) {
			return $this->error( 'not_verified', 503 );
		}
		$extension = $opted_in ? $extensions[ self::NAMESPACE ] : null;
		$contract = $extension;
		// Woo inserts null for the omitted response-only property. It is not
		// a readiness/permission flag; explicit non-null values stay rejected.
		if ( is_array( $contract ) && array_key_exists( 'qa_isolation', $contract ) && null === $contract['qa_isolation'] ) {
			unset( $contract['qa_isolation'] );
		}
		$native = $extensions['mobishop_native_checkout50'] ?? null;
		$body = $request->get_json_params();
		if ( ! $owned_customer || ! is_array( $extension ) || count( $contract ) !== 2 || 51 !== ( $extension['protocol'] ?? null ) || ( $extension['run'] ?? null ) !== $this->config['run'] || ! is_array( $body ) || ( $body['extensions'][ self::NAMESPACE ] ?? null ) !== $extension || ! is_array( $native ) || 50 !== ( $native['protocol'] ?? null ) || ( $native['confirmed']['total_price'] ?? null ) !== '0' || ( $native['confirmed']['currency_code'] ?? null ) !== $this->config['currency'] || ( $native['confirmed']['currency_minor_unit'] ?? null ) !== $this->config['minor_unit'] || ( $body['payment_method'] ?? '' ) !== '' || ! empty( $body['payment_data'] ) || ( $body['billing_address']['email'] ?? null ) !== $this->config['customer_email'] ) {
			return $this->error( 'not_owned_nonpaid_fixture', 403 );
		}
		if ( ! $this->stored_cart_matches( $request, $customer ) ) {
			return $this->error( 'not_owned_nonpaid_fixture', 403 );
		}
		$this->active = array( 'request' => $request, 'customer' => $customer, 'order_id' => 0, 'conflict' => false );
		return $result; // Safety50 invokes the normal Store API exactly once.
	}

	/** Tag BEFORE first draft persistence; never throw inside WC_Order::save(). */
	public function mark_before_first_save( $order, $data_store = null ): void {
		unset( $data_store );
		if ( ! $this->active || ! $order instanceof WC_Order || 'shop_order' !== $order->get_type() || 'store-api' !== $order->get_created_via() ) {
			return;
		}
		// Even a malformed QA draft must be quarantined by ERP, not imported.
		$order->update_meta_data( self::MARKER, $this->signed_marker() );
		if ( (int) $order->get_customer_id() !== $this->active['customer'] || ( $this->active['order_id'] && (int) $order->get_id() !== $this->active['order_id'] ) ) {
			$this->active['conflict'] = true;
		}
	}

	/** Installed source must prove this hook precedes holds/payment/fulfilment. */
	public function validate_nonpaid_order( $order, $errors = null ): void {
		unset( $errors );
		if ( ! $this->active ) {
			return;
		}
		$valid = $this->ready() && ! $this->active['conflict'] && $order instanceof WC_Order && $this->authenticated_customer( $this->active['request'] ) === $this->active['customer'] && $this->recognizes_marker( $order ) && (int) $order->get_customer_id() === $this->config['customer_id'] && $order->get_billing_email() === $this->config['customer_email'] && $order->get_currency() === $this->config['currency'] && wc_get_price_decimals() === $this->config['minor_unit'] && self::zero( $order->get_total( 'edit' ) ) && '' === $order->get_payment_method() && '' === $order->get_transaction_id() && ! $order->needs_payment() && ! $order->get_items( 'shipping' ) && ! $order->get_items( 'fee' ) && ! $order->get_items( 'coupon' );
		$items = $valid ? $order->get_items( 'line_item' ) : array();
		if ( 1 !== count( $items ) ) {
			$valid = false;
		}
		foreach ( $items as $item ) {
			if ( (int) $item->get_product_id() !== $this->config['product_id'] || (int) $item->get_variation_id() !== 0 || ! self::one( $item->get_quantity() ) || ! self::zero( $item->get_total() ) || ! self::zero( $item->get_subtotal() ) || ! self::zero( $item->get_total_tax() ) || ! self::zero( $item->get_subtotal_tax() ) ) {
				$valid = false;
			}
		}
		$persisted = $order instanceof WC_Order && (int) $order->get_id() > 0 ? wc_get_order( (int) $order->get_id() ) : false;
		if ( ! $valid || ! $persisted instanceof WC_Order || ! $this->recognizes_marker( $persisted ) || (int) $persisted->get_customer_id() !== $this->config['customer_id'] || ( $this->active['order_id'] && (int) $order->get_id() !== $this->active['order_id'] ) ) {
			throw new \Automattic\WooCommerce\StoreApi\Exceptions\RouteException( 'mobishop_native_qa51_isolation_unproven', 'The isolated nonpaid QA order is not verified. No payment is allowed.', 503 );
		}
		$this->active['order_id'] = (int) $order->get_id();
	}

	/** Suppress ONLY server-signed owned QA orders, even after request cleanup. */
	public function allow_email( $enabled, $object = null, $email = null ) {
		$order = $object instanceof WC_Order ? $object : ( $email->object ?? null );
		return $order instanceof WC_Order && $this->recognizes_marker( $order ) ? false : $enabled;
	}

	public function allow_stock_reduction( $allowed, $order ) {
		return $order instanceof WC_Order && $this->recognizes_marker( $order ) ? false : $allowed;
	}

	public function allow_webhook( $allowed, $webhook, $arg ) {
		if ( ! is_object( $webhook ) || ! is_callable( array( $webhook, 'get_resource' ) ) || 'order' !== $webhook->get_resource() || ! is_scalar( $arg ) || ! preg_match( '/^[1-9][0-9]{0,17}$/D', (string) $arg ) ) {
			return $allowed;
		}
		$order = wc_get_order( (int) $arg );
		return $order instanceof WC_Order && $this->recognizes_marker( $order ) ? false : $allowed;
	}

	public function finish_request( $response, $server, WP_REST_Request $request ) {
		unset( $server );
		if ( $this->active && $request === $this->active['request'] ) {
			$this->active = null;
			if ( $response instanceof WP_REST_Response ) {
				$response->header( 'Cache-Control', 'private, no-store, max-age=0' );
			}
		}
		return $response;
	}

	/** Historical recognition does not expire if probe readiness later fails. */
	public function recognizes_marker( WC_Order $order ): bool {
		$marker = $order->get_meta( self::MARKER, true );
		return $this->valid_configuration() && is_array( $marker ) && $marker === $this->signed_marker();
	}

	/** No implicit activation/config lookup; preserve historical signed scopes. */
	public static function recognizes_registered_order( WC_Order $order ): bool {
		foreach ( self::$registered_guards as $guard ) {
			if ( $guard->recognizes_marker( $order ) ) {
				return true;
			}
		}
		return false;
	}

	public function public_scope(): array {
		$scope = $this->config;
		unset( $scope['hmac_key'] );
		return $scope;
	}

	public static function canonical_scope( array $config ): string {
		return 'mobishop-native-qa51|' . ( $config['origin'] ?? '' ) . '|' . ( $config['run'] ?? '' ) . '|' . ( $config['customer_id'] ?? '' ) . '|' . ( $config['product_id'] ?? '' ) . '|' . ( $config['currency'] ?? '' ) . '|' . ( $config['minor_unit'] ?? '' );
	}

	private function signed_marker(): array {
		return array( 'schema' => 51, 'origin' => $this->config['origin'], 'run' => $this->config['run'], 'customer_id' => $this->config['customer_id'], 'product_id' => $this->config['product_id'], 'currency' => $this->config['currency'], 'minor_unit' => $this->config['minor_unit'], 'proof' => hash_hmac( 'sha256', self::canonical_scope( $this->config ), $this->config['hmac_key'] ) );
	}

	private function valid_configuration(): bool {
		$c = $this->config;
		return ( $c['origin'] ?? '' ) === 'https://staging.kidiastore.com' && is_string( $c['run'] ?? null ) && preg_match( '/^[a-f0-9]{32}$/D', $c['run'] ) && is_int( $c['customer_id'] ?? null ) && $c['customer_id'] > 0 && is_int( $c['product_id'] ?? null ) && $c['product_id'] > 0 && is_string( $c['hmac_key'] ?? null ) && preg_match( '/^[a-f0-9]{64}$/D', $c['hmac_key'] ) && is_string( $c['customer_email'] ?? null ) && preg_match( '/^[a-z0-9._+-]{1,80}@example\.invalid$/D', $c['customer_email'] ) && is_string( $c['currency'] ?? null ) && preg_match( '/^[A-Z]{3}$/D', $c['currency'] ) && is_int( $c['minor_unit'] ?? null ) && $c['minor_unit'] >= 0 && $c['minor_unit'] <= 8;
	}

	private function environment_matches(): bool {
		return function_exists( 'wp_get_environment_type' ) && 'staging' === wp_get_environment_type() && function_exists( 'wp_is_using_https' ) && wp_is_using_https() && rtrim( home_url( '/' ), '/' ) === $this->config['origin'] && rtrim( site_url( '/' ), '/' ) === $this->config['origin'];
	}

	private function customer_matches(): bool {
		$user = get_userdata( $this->config['customer_id'] );
		return $user && $user->user_email === $this->config['customer_email'] && array( 'customer' ) === array_values( (array) $user->roles ) && get_user_meta( $this->config['customer_id'], '_mobishop_native_qa51_customer', true ) === $this->config['run'];
	}

	private function fixture_matches(): bool {
		$product = wc_get_product( $this->config['product_id'] );
		return $product instanceof WC_Product && $product->is_type( 'simple' ) && $product->get_status() === 'publish' && $product->get_catalog_visibility() === 'hidden' && $product->is_virtual() && ! $product->is_downloadable() && ! $product->managing_stock() && ! $product->is_taxable() && $product->is_purchasable() && self::zero( $product->get_price( 'edit' ) ) && $product->get_sku() === 'MOBISHOP-NATIVE-QA51-' . $this->config['run'] && $product->get_meta( '_mobishop_native_qa51_fixture', true ) === $this->config['run'];
	}

	private function authenticated_customer( WP_REST_Request $request ): ?int {
		if ( ! class_exists( 'MobiShop_Customer_Auth_Endpoint' ) || ! function_exists( 'wp_is_using_https' ) || ! wp_is_using_https() ) {
			return null;
		}
		$context = ( new MobiShop_Customer_Auth_Endpoint() )->session_context_from_request( $request );
		return ! is_wp_error( $context ) && is_array( $context ) && is_int( $context['user_id'] ?? null ) && $context['user_id'] > 0 && $context['user_id'] === get_current_user_id() ? $context['user_id'] : null;
	}

	/** Read authenticated persisted Woo session; no cart/session writes. */
	private function stored_cart_matches( WP_REST_Request $request, int $customer ): bool {
		$class = '\\Automattic\\WooCommerce\\StoreApi\\Utilities\\CartTokenUtils';
		$token = (string) $request->get_header( 'Cart-Token' );
		if ( ! class_exists( $class ) || strlen( $token ) > 4096 || ! $class::validate_cart_token( $token ) ) {
			return false;
		}
		$payload = $class::get_cart_token_payload( $token );
		$user = (string) ( $payload['user_id'] ?? '' );
		// The current Woo generator is t_ plus 30 lower-case hex characters.
		// Retain the previous exact formats, never arbitrary website UUIDs;
		// signed token and persisted fixture/customer ownership remain required.
		if ( 'store-api' !== ( $payload['iss'] ?? '' ) || (int) ( $payload['exp'] ?? 0 ) <= time() || ! preg_match( '/^(?:[1-9][0-9]{0,17}|t_[a-f0-9]{30}|(?:t_)?[a-f0-9]{32})$/D', $user ) || ( ctype_digit( $user ) && $user !== (string) $customer ) ) {
			return false;
		}
		$db = $GLOBALS['wpdb'];
		if ( ! preg_match( '/^[A-Za-z0-9_]+$/D', (string) $db->prefix ) ) {
			return false;
		}
		$row = $db->get_row( $db->prepare( "SELECT session_value, session_expiry FROM `{$db->prefix}woocommerce_sessions` WHERE session_key = %s", $user ), ARRAY_A );
		if ( ! is_array( $row ) || ! empty( $db->last_error ) || (int) ( $row['session_expiry'] ?? 0 ) <= time() || ! is_string( $row['session_value'] ?? null ) ) {
			return false;
		}
		$session = @unserialize( $row['session_value'], array( 'allowed_classes' => false ) );
		if ( ! is_array( $session ) ) {
			return false;
		}
		foreach ( array( 'cart', 'customer', 'applied_coupons' ) as $key ) {
			if ( is_string( $session[ $key ] ?? null ) ) {
				$session[ $key ] = @unserialize( $session[ $key ], array( 'allowed_classes' => false ) );
			}
		}
		$owner = $session['customer']['id'] ?? null;
		if ( ! ( is_int( $owner ) || is_string( $owner ) ) || ! in_array( (string) $owner, array( '0', (string) $customer ), true ) || ! is_array( $session['cart'] ?? null ) || count( $session['cart'] ) !== 1 || ! is_array( $session['applied_coupons'] ?? null ) || $session['applied_coupons'] ) {
			return false;
		}
		$item = reset( $session['cart'] );
		return is_array( $item ) && self::same_id( $item['product_id'] ?? null, $this->config['product_id'] ) && self::same_id( $item['variation_id'] ?? null, 0 ) && self::one( $item['quantity'] ?? null ) && self::zero( $item['line_subtotal'] ?? null ) && self::zero( $item['line_total'] ?? null ) && self::zero( $item['line_subtotal_tax'] ?? null ) && self::zero( $item['line_tax'] ?? null );
	}

	private static function same_id( $value, int $expected ): bool {
		return ( is_int( $value ) && $value === $expected ) || ( is_string( $value ) && (string) $expected === $value );
	}

	private static function zero( $value ): bool {
		return ( is_int( $value ) && 0 === $value ) || ( is_float( $value ) && 0.0 === $value ) || ( is_string( $value ) && 1 === preg_match( '/^0(?:\.0+)?$/D', $value ) );
	}

	private static function one( $value ): bool {
		return ( is_int( $value ) && 1 === $value ) || ( is_float( $value ) && 1.0 === $value ) || ( is_string( $value ) && 1 === preg_match( '/^1(?:\.0+)?$/D', $value ) );
	}

	private function error( string $reason, int $status ): WP_REST_Response {
		$response = new WP_REST_Response( array( 'code' => 'mobishop_native_qa51_' . $reason, 'message' => 'Staging nonpaid QA isolation is not established. No order was submitted by this guard.', 'qa_isolation' => false ), $status );
		$response->header( 'Cache-Control', 'private, no-store, max-age=0' );
		return $response;
	}
}
